-- =============================================================================
-- 20_constraints.sql  —  add the rules whose absence let each fault happen
-- =============================================================================
--
-- WHAT THIS FILE DOES
--   The diagnosis asked, for every fault: "which rule, had it existed from the start,
--   would have made this impossible?" This file adds those rules, so that once the data
--   has been cleaned (sql/10), the same faults cannot come back. From now on the
--   DATABASE refuses bad data at the moment it is written, whatever program writes it.
--
-- THE KINDS OF RULE USED (in plain words)
--   NOT NULL      the column must always have a value
--   FOREIGN KEY   a value must point at a row that really exists in another table
--                 (e.g. an order's customer_id must be a real customer)
--   CHECK         a value must pass a test (e.g. stock is never below zero)
--   UNIQUE        no two rows may have the same value
--
-- EVERY RULE HAS A NAME (e.g. products_stock_not_negative), so when one refuses a write,
-- the error message tells Nana's team exactly which rule fired.
--
-- DESIGNED AROUND race_test.py, which must run unmodified:
--   * it inserts test products with category_id NULL
--       -> products.category_id stays optional (no NOT NULL)
--   * it cleans up by deleting order_items, then orders, then inventory_log, then products
--       -> the foreign keys use PostgreSQL's default behaviour ("refuse to delete a row
--          that other rows still point at"), and that deletion order always satisfies it.
-- =============================================================================

\echo '== 20_constraints: types, keys and rules'

-- One transaction: if any rule can't be added, none are, and the database is unchanged.
BEGIN;

-- =============================================================================
-- TIME ZONES
-- =============================================================================
-- The original columns were "timestamp" with no time zone: a time with no record of
-- WHICH clock it came from. "timestamptz" stores the moment unambiguously.
-- USING … AT TIME ZONE 'Africa/Accra' tells PostgreSQL how to read the old values:
-- "these were Accra times". Accra is UTC+0 all year (no daylight saving), so no stored
-- time actually changes today. The benefit is for the future: if any system ever writes
-- times from another zone, comparisons and monthly totals stay correct.
-- (Assumption documented in data_findings.md, "Could not verify".)
ALTER TABLE orders        ALTER COLUMN order_date    TYPE timestamptz USING order_date    AT TIME ZONE 'Africa/Accra';
ALTER TABLE customers     ALTER COLUMN registered_at TYPE timestamptz USING registered_at AT TIME ZONE 'Africa/Accra';
ALTER TABLE products      ALTER COLUMN created_at    TYPE timestamptz USING created_at    AT TIME ZONE 'Africa/Accra';
ALTER TABLE inventory_log ALTER COLUMN created_at    TYPE timestamptz USING created_at    AT TIME ZONE 'Africa/Accra';

-- =============================================================================
-- AUTOMATIC IDS
-- =============================================================================
-- The tables had primary keys but nothing to GENERATE them, so the old application
-- picked ids itself. That is unsafe under load: two simultaneous orders could pick the
-- same next id. place_order needs the database to hand out ids, because the database
-- can guarantee each one is used once, even with 400 buyers at the same moment.
--
-- GENERATED BY DEFAULT AS IDENTITY: if an INSERT doesn't give an id, PostgreSQL supplies
-- the next number. ("BY DEFAULT" rather than "ALWAYS" still allows an explicit id, which
-- the historical data and the cleanup need.)
ALTER TABLE orders        ALTER COLUMN order_id      ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE order_items   ALTER COLUMN order_item_id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE inventory_log ALTER COLUMN log_id        ADD GENERATED BY DEFAULT AS IDENTITY;

-- A new identity starts counting at 1, but ids up to ~650,000 already exist. setval
-- moves each counter past the highest id EVER used, including rows now in quarantine,
-- so a new order can never reuse an old order's number.
-- pg_get_serial_sequence finds the counter PostgreSQL created for the column;
-- greatest(…, 1) also covers an empty table.
SELECT setval(pg_get_serial_sequence('orders', 'order_id'),
              greatest((SELECT max(order_id) FROM orders), (SELECT max(order_id) FROM quarantine_orders), 1));
SELECT setval(pg_get_serial_sequence('order_items', 'order_item_id'),
              greatest((SELECT max(order_item_id) FROM order_items), (SELECT max(order_item_id) FROM quarantine_order_items), 1));
SELECT setval(pg_get_serial_sequence('inventory_log', 'log_id'),
              greatest((SELECT max(log_id) FROM inventory_log), (SELECT max(log_id) FROM quarantine_inventory_log), 1));

-- If an INSERT doesn't say when something happened, use "now".
ALTER TABLE inventory_log ALTER COLUMN created_at SET DEFAULT now();
ALTER TABLE orders        ALTER COLUMN order_date SET DEFAULT now();

-- =============================================================================
-- REQUIRED VALUES (NOT NULL)
-- =============================================================================
-- In the original schema EVERY column except the ids could be left empty. These are the
-- columns where an empty value would break something: an order with no customer can't
-- be in anyone's spending; a stock movement with no quantity can't be audited.
ALTER TABLE categories    ALTER COLUMN category_name  SET NOT NULL;
ALTER TABLE products      ALTER COLUMN product_name   SET NOT NULL,
                          ALTER COLUMN price          SET NOT NULL,
                          ALTER COLUMN stock_quantity SET NOT NULL;
ALTER TABLE customers     ALTER COLUMN full_name      SET NOT NULL;
ALTER TABLE orders        ALTER COLUMN customer_id    SET NOT NULL,
                          ALTER COLUMN order_date     SET NOT NULL,
                          ALTER COLUMN status         SET NOT NULL,
                          ALTER COLUMN total_amount   SET NOT NULL;
ALTER TABLE order_items   ALTER COLUMN order_id       SET NOT NULL,
                          ALTER COLUMN product_id     SET NOT NULL,
                          ALTER COLUMN quantity       SET NOT NULL;
-- order_items.unit_price stays nullable: 148 historical lines lost their price (F-13) and the
-- correct value is unknown. New lines always carry a price (place_order writes it).
ALTER TABLE inventory_log ALTER COLUMN product_id     SET NOT NULL,
                          ALTER COLUMN change_qty     SET NOT NULL,
                          ALTER COLUMN reason         SET NOT NULL,
                          ALTER COLUMN created_at     SET NOT NULL;

-- =============================================================================
-- RELATIONSHIPS (FOREIGN KEYS)  —  stop F-06, F-07, F-12, F-15 recurring
-- =============================================================================
-- The schema had six relationships and zero foreign keys, which is how 210 orders came
-- to point at no customer, 692 lines at no order, 120 movements at no product and one
-- category at no parent. Each line below says: "this column may only hold a value that
-- exists in that other table". Adding one checks every existing row first; that is why
-- sql/10 had to remove the orphans before this file runs.
--
-- (products.category_id may still be NULL, an uncategorised product. A foreign key
-- only checks values that are present.)
ALTER TABLE categories    ADD CONSTRAINT categories_parent_fk     FOREIGN KEY (parent_id)   REFERENCES categories (category_id);
ALTER TABLE products      ADD CONSTRAINT products_category_fk     FOREIGN KEY (category_id) REFERENCES categories (category_id);
ALTER TABLE orders        ADD CONSTRAINT orders_customer_fk       FOREIGN KEY (customer_id) REFERENCES customers (customer_id);
ALTER TABLE order_items   ADD CONSTRAINT order_items_order_fk     FOREIGN KEY (order_id)    REFERENCES orders (order_id);
ALTER TABLE order_items   ADD CONSTRAINT order_items_product_fk   FOREIGN KEY (product_id)  REFERENCES products (product_id);
ALTER TABLE inventory_log ADD CONSTRAINT inventory_log_product_fk FOREIGN KEY (product_id)  REFERENCES products (product_id);

-- INDEXES on those columns. An index is like the index at the back of a book: it lets
-- PostgreSQL jump straight to "all lines of order 500230" instead of reading every row.
-- PostgreSQL does NOT create these for foreign keys by itself. Without them:
--   * every join from orders to their lines would read the whole order_items table, and
--   * every delete of a parent (e.g. race_test's cleanup deleting a product) would scan
--     the whole child table to check nothing still points at it.
CREATE INDEX order_items_order_id_idx   ON order_items   (order_id);
CREATE INDEX order_items_product_id_idx ON order_items   (product_id);
-- (product_id, created_at): finds one product's movements AND keeps them in date order,
-- which is how an auditor walks a product's history.
CREATE INDEX inventory_log_product_idx  ON inventory_log (product_id, created_at);
CREATE INDEX orders_customer_id_idx     ON orders        (customer_id);
CREATE INDEX products_category_id_idx   ON products      (category_id);
CREATE INDEX categories_parent_id_idx   ON categories    (parent_id);

-- =============================================================================
-- VALUE RULES (CHECK)  —  stop F-03, F-04, F-13, F-14 recurring
-- =============================================================================
-- Stock can never go below zero. This is the SAFETY NET under place_order (ADR-001):
-- place_order never tries to oversell, but if any other program ever does, the database
-- refuses with an error instead of quietly recording −1.
ALTER TABLE products ADD CONSTRAINT products_stock_not_negative CHECK (stock_quantity >= 0);  -- safety net under place_order
ALTER TABLE products ADD CONSTRAINT products_price_positive     CHECK (price > 0);
-- A cancelled order keeps its original total (status marks the cancellation), so every
-- order's total is positive. Confirmed on the data: 0 orders had a total of 0 or less.
ALTER TABLE orders   ADD CONSTRAINT orders_total_positive       CHECK (total_amount > 0);
-- Only these five statuses exist. This rule is what stops F-04 (15 spellings) from ever
-- happening again: 'Cancelled', ' completed' or 'canceled' are now refused on entry.
ALTER TABLE orders   ADD CONSTRAINT orders_status_valid
    CHECK (status IN ('pending', 'shipped', 'completed', 'cancelled', 'refunded'));
ALTER TABLE order_items ADD CONSTRAINT order_items_quantity_positive CHECK (quantity > 0);
-- 152 historical lines have a price of 0 (F-13, price lost, correct value unknown).
-- NOT VALID: the rule applies to every new or changed line but does not reject history.
-- (Without NOT VALID, PostgreSQL would check the old rows, find the zeros, and refuse
-- to add the rule at all.)
ALTER TABLE order_items ADD CONSTRAINT order_items_unit_price_positive CHECK (unit_price > 0) NOT VALID;
-- The six reasons found in the data, plus 'cancellation', written by cancel_order (sql/40).
ALTER TABLE inventory_log ADD CONSTRAINT inventory_log_reason_valid
    CHECK (reason IN ('sale', 'restock', 'return', 'correction', 'damage', 'stock_take', 'cancellation'));
-- A category may not be its own parent. NOTE what this can't do: a CHECK sees one row
-- at a time, so it can't spot a loop across two rows (9001 -> 9002 -> 9001, F-08).
-- That loop is detected instead (sql/60 and v_data_health in sql/70).
ALTER TABLE categories ADD CONSTRAINT categories_not_own_parent CHECK (parent_id <> category_id);

-- =============================================================================
-- IDENTITY RULES (UNIQUE)  —  stop F-05 recurring
-- =============================================================================
-- Uniqueness on the NORMALISED email: a rule on raw email would have stopped only 299 of the
-- 533 duplicate groups, because the other 234 differ only by capitals or spaces.
-- A UNIQUE INDEX on an expression, lower(trim(email)), compares emails the same way the
-- diagnosis did, so 'Ama@Mail.com ' and 'ama@mail.com' count as the same address.
CREATE UNIQUE INDEX customers_email_unique ON customers (lower(trim(email)));
-- Two categories with the same name under the same parent are the same category.
-- NULLS NOT DISTINCT makes two top-level categories with the same name count as duplicates too.
-- (Normally two NULLs count as "different", so two top-level "Electronics" would slip
-- through. NULLS NOT DISTINCT, available since PostgreSQL 15, treats them as equal.)
CREATE UNIQUE INDEX categories_name_per_parent_unique
    ON categories (parent_id, lower(trim(category_name))) NULLS NOT DISTINCT;

COMMIT;

\echo '== 20_constraints: done'
